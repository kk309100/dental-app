-- 在庫数の単位（stock_unit）を追加
-- 2026-08-31
--
-- 目的: これまで「入り数の単位（unit）」しか設定できず、在庫数（stock_quantity）の
--       単位は画面上「箱」に固定表示されていた。これを分離し、
--       在庫数の単位も商品ごとに自由に設定できるようにする。
--
-- 例）「グローブ」を10箱在庫している場合
--   stock_quantity = 10
--   stock_unit     = "箱"      ← 今回追加（在庫数の単位）
--   units_per_package = 50
--   unit           = "枚"      ← 既存（入り数の単位）
--
-- Supabase Studio の SQL Editor で1回実行してください。
-- ============================================================================

ALTER TABLE clinic_inventory_items ADD COLUMN IF NOT EXISTS stock_unit text;
