-- 見積書の明細に「仕入価格」を保存できるようにする
-- 2026-09-16
--
-- 背景: 見積作成画面では仕入価格（社内詳細）を入力できるが、quote_items
--       テーブルに保存するカラムが無かったため、商品マスタに紐づいていない
--       明細（手入力の一回限りの商品等）を編集しようとすると仕入価格が
--       ¥0に消えてしまっていた。
-- Supabase Studio の SQL Editor で1回実行してください。
-- ============================================================================

ALTER TABLE IF EXISTS quote_items ADD COLUMN IF NOT EXISTS cost integer;
